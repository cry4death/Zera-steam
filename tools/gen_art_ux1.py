"""Небольшие пиктограммы выбора и состояния оружия, без случайности."""
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1] / "art"
C = "#e0ded1"


def icon(name, lines=(), boxes=()):
    image = Image.new("RGBA", (16, 16))
    draw = ImageDraw.Draw(image)
    for points in lines:
        draw.line(points, fill=C, width=1)
    for box in boxes:
        draw.rectangle(box, outline=C)
    image.save(ROOT / f"ux1_{name}.png")


